// Writes the catalog of the installed Strudel's functions (strudel-catalog, #69): docs/strudel/functions.json,
// docs/strudel/coverage.json and docs/STRUDEL-FUNCTIONS.md. docs/strudel/variety.json is written by hand and only read.
//   npm run catalog:strudel
// The output depends only on the installed packages and the generated code: two runs give the same files.
import fs from 'node:fs';
import path from 'node:path';
import { readFunctions, lookup, ROOT } from './strudel-functions.mjs';
import { collectCalls, coverageOf, KINDS, RADIO_MINUTES } from './strudel-code.mjs';
import { LIBRARY, NAMES } from '../src/song/functions.js';

export const FILES = {
  functions: path.join(ROOT, 'docs/strudel/functions.json'),
  coverage: path.join(ROOT, 'docs/strudel/coverage.json'),
  variety: path.join(ROOT, 'docs/strudel/variety.json'),
  page: path.join(ROOT, 'docs/STRUDEL-FUNCTIONS.md'),
};
export const json = x => JSON.stringify(x, null, 2) + '\n';
export const readVariety = () => JSON.parse(fs.readFileSync(FILES.variety, 'utf8'));

const short = pkg => pkg.replace(/^@strudel\//, '');
const cell = s => String(s).replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');
const anchor = name => `fn-${name.replace(/[^\w-]/g, c => `_${c.charCodeAt(0).toString(16)}`)}`;
const writtenBy = c => (c ? KINDS.filter(k => c[k]).map(k => `${k} ${c[k]}`).join(', ') : 'never');

// the variety notes by entry name (a note may name a synonym, like seg for segment, or a label)
export function varietyByEntry(variety, lookupMap, labels) {
  const out = {}, missing = [];
  for (const [name, v] of Object.entries(variety)) {
    if (labels.some(l => l.label === name)) continue;
    const entry = lookupMap.get(name);
    if (!entry) { missing.push(name); continue; }
    (out[entry] ||= []).push({ name, ...v });
  }
  return { byEntry: out, missing };
}

export function page(catalog, coverage, variety) {
  const L = lookup(catalog), { byEntry } = varietyByEntry(variety, L, catalog.labels), cov = coverage.functions;
  const fs_ = catalog.functions, documented = fs_.filter(f => f.documented).length, written = fs_.filter(f => cov[f.name]).length;
  const never = fs_.filter(f => !cov[f.name]);
  const out = [
    '# Strudel functions',
    '',
    `> ${catalog.source.text}`,
    `> Project: ${catalog.source.url} · source: ${catalog.source.repository}.`,
    '',
    'Generated by `npm run catalog:strudel` from the installed packages and the code the app generates: do not edit by hand. The "useful for variety" notes are written by hand in `docs/strudel/variety.json`; full examples are in `docs/strudel/functions.json`. `npm run check:strudel` fails when generated code calls a function that is not here.',
    '',
    '## Summary',
    '',
    `- Functions: ${fs_.length} (${L.size} names with synonyms)`,
    `- Documented (a \`@name\` comment, as in the Strudel reference): ${documented}`,
    `- Undocumented (registered or declared with no \`@name\` comment): ${fs_.length - documented}`,
    `- Written by the app: ${written}`,
    `- Never written: ${never.length}`,
    `- Code read for the coverage: ${coverage.source.codes} texts (every song in \`songs/\` and \`songs/examples/\`, every live build step in each profile and technical functions preset, one ${RADIO_MINUTES}-minute radio session per style with seed \`catalog-<style>\`, the helpers prelude)`,
    '',
    '"Written by" counts the sources that write a function: songs (compiled songs), live (songs\' live builds), radio (radio songs and their builds), prelude (the app\'s helpers prelude).',
    '',
    '## App functions',
    '',
    'Functions the app registers for the code it writes (`src/song/writer.js`, song-functions). None of them is a Strudel name or synonym: `npm run check:strudel` fails when one is. `.o()`, `.drive()` and `.voice()` are Strudel\'s again.',
    '',
    '| Function | What it does |',
    '| --- | --- |',
    '| `chan(name)` | bus and visual of a track: `.orbit(n).analyze(name)` (Technical functions: bus) |',
    '| `crunch(x)` | distortion with its volume: `.distort(x).distortvol(.5)` (Technical functions: distortion) |',
    ...LIBRARY.map(f => `| \`${f.name}(${f.params.join(', ')})\` | ${cell(f.about.en)}: \`${f.chain}\` (library) |`),
    '',
    `Song functions (Technical functions: song) fold effect chains that repeat in a song; their names come from word lists in \`src/song/functions.js\` (${Object.keys(NAMES.themes).length} themes, ${Object.keys(NAMES.tracks).length} track types, generic words), picked by the song id. Their definitions are in the hidden code and in the code copied or opened in Strudel.`,
    '',
    '## Labels',
    '',
    'Line labels the REPL handles (`@strudel/core` repl.mjs). They are not functions.',
    '',
    '| Label | What it does | Useful for variety |',
    '| --- | --- | --- |',
    ...catalog.labels.map(l => `| \`${l.label}\` | ${cell(l.note)} | ${variety[l.label] && variety[l.label].useful ? cell(`yes: ${variety[l.label].note}`) : ''} |`),
    '',
    '## Never written',
    '',
    never.map(f => `[\`${f.name}\`](#${anchor(f.name)})`).join(', '),
    '',
    '## Coverage',
    '',
    '| Function | Synonyms | Package | Written by | Useful for variety |',
    '| --- | --- | --- | --- | --- |',
  ];
  for (const f of fs_) {
    const c = cov[f.name], v = byEntry[f.name];
    const by = c ? `${writtenBy(c)}${c.as.length > 1 || c.as[0] !== f.name ? ` (as ${c.as.map(x => `\`${x}\``).join(', ')})` : ''}` : 'never';
    const useful = v ? v.filter(x => x.useful).map(x => `yes${x.name !== f.name ? ` (\`${x.name}\`)` : ''}: ${x.note}`).join(' ') : '';
    out.push(`| [\`${f.name}\`](#${anchor(f.name)})${f.documented ? '' : ' (undocumented)'} | ${f.synonyms.map(s => `\`${s}\``).join(', ')} | ${short(f.package)} | ${by} | ${cell(useful)} |`);
  }
  out.push('', '## Functions', '');
  for (const f of fs_) {
    out.push(`<a id="${anchor(f.name)}"></a>`, '', `### ${f.name}`, '');
    const meta = [`\`${short(f.package)}/${f.file}\``];
    if (f.synonyms.length) meta.push(`synonyms: ${f.synonyms.map(s => `\`${s}\``).join(', ')}`);
    if (!f.documented) meta.push('undocumented');
    out.push(meta.join(' · '), '');
    if (f.description) out.push(f.description, '');
    if (f.params.length) { out.push(...f.params.map(p => `- \`${p.name}\`${p.type ? ` (${p.type})` : ''}${p.description ? `: ${p.description}` : ''}`), ''); }
    if (f.examples.length) out.push('```js', f.examples[0], '```', '');
  }
  return out.join('\n').replace(/\n{3,}/g, '\n\n').replace(/\n*$/, '\n');
}

// builds everything: { catalog, coverage, files: { path → text } }
export function build() {
  const catalog = readFunctions(), L = lookup(catalog);
  const coverage = coverageOf(catalog, collectCalls(), L);
  const { unknown, ...stored } = coverage;
  return {
    catalog, coverage, unknown,
    files: { [FILES.functions]: json(catalog), [FILES.coverage]: json(stored), [FILES.page]: page(catalog, stored, readVariety()) },
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  const t = Date.now(), { catalog, coverage, unknown, files } = build();
  for (const [file, text] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    fs.writeFileSync(file, text);
    console.log(`${old === text ? 'same   ' : 'written'}  ${path.relative(ROOT, file)}`);
  }
  const fn = catalog.functions, documented = fn.filter(f => f.documented).length, written = Object.keys(coverage.functions).length;
  console.log(`\n${fn.length} functions (${documented} documented, ${fn.length - documented} undocumented), ${written} written by the app, ${fn.length - written} never written; ${coverage.source.codes} code texts read in ${((Date.now() - t) / 1000).toFixed(1)} s`);
  if (Object.keys(unknown).length) console.log(`names not in the catalog (npm run check:strudel): ${Object.keys(unknown).join(', ')}`);
}
