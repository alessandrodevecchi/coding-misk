// Grown lengths of the built-in songs for the song cards (src/live/card-duration.js): a song that declares Crescendo or
// Live coder shows the length it plays with its own profile, and growing it in the page would freeze the song list.
// The lengths are computed here once and kept in src/library/song-durations.json, by key: the song, its profile, the
// versions of the growth and the voice instrument's context of the page (the committed samples of public/samples, no
// measured lengths, each language). A page with another context (voices made with npm run voices) grows the songs on
// screen in the grow worker instead.
//   node tools/song-durations.mjs write   rewrite the file
//   node tools/song-durations.mjs check   exit 1 when the file is stale (songs, growth rules, SHAPES_VERSION changed)
import fs from 'node:fs';
import path from 'node:path';
import { songFiles } from './songs-dir.mjs';
import { setSpokenContext } from '../src/song/spoken.js';
import { durationKey, grownDuration, growingProfile } from '../src/live/card-duration.js';

const OUT = 'src/library/song-durations.json';
const LANGS = ['en', 'it'];
const mode = process.argv[2];
if (mode !== 'write' && mode !== 'check') { console.error('usage: node tools/song-durations.mjs write|check'); process.exit(2); }

// the samples manifest the dev server serves (vite.config.js), without the git-ignored spoken samples (say_*)
function committedManifest() {
  const dir = path.join('public', 'samples'), out = { _base: '/samples/' }, AUDIO = /\.(wav|mp3|ogg|flac|m4a|aac)$/i, clean = n => n.replace(/[^\w-]/g, '_');
  if (!fs.existsSync(dir)) return out;
  for (const name of fs.readdirSync(dir).sort()) {
    if (/^say_/.test(name)) continue;
    const p = path.join(dir, name);
    if (fs.statSync(p).isDirectory()) { const files = fs.readdirSync(p).filter(f => AUDIO.test(f)).sort(); if (files.length) out[clean(name)] = files.map(f => encodeURI(`${name}/${f}`)); }
    else if (AUDIO.test(name)) out[clean(name.replace(AUDIO, ''))] = [encodeURI(name)];
  }
  return out;
}

const styles = Object.fromEntries(fs.readdirSync('styles').filter(f => f.endsWith('.json')).sort().map(f => JSON.parse(fs.readFileSync(`styles/${f}`, 'utf8'))).map(r => [r.id, r]));
const files = committedManifest(), lengths = {};
const songs = songFiles('songs').map(f => JSON.parse(fs.readFileSync(f, 'utf8'))).filter(s => s && s.id && growingProfile(s));
const t0 = Date.now(), entries = {};
for (const lang of LANGS) {
  setSpokenContext({ files, lengths, lang, styles });
  for (const song of songs) {
    const key = durationKey(song, { files, lengths, lang }), d = grownDuration(song, styles);
    if (d) entries[key] = { id: song.id, lang, ...d };
  }
}
const sorted = Object.fromEntries(Object.entries(entries).sort(([, a], [, b]) => a.id.localeCompare(b.id) || a.lang.localeCompare(b.lang)));
const text = JSON.stringify({ note: 'generated by tools/song-durations.mjs, do not edit', entries: sorted }, null, 1) + '\n';
console.log(`${songs.length} growing songs × ${LANGS.length} languages, ${Object.keys(sorted).length} lengths in ${((Date.now() - t0) / 1000).toFixed(1)} s`);
if (mode === 'write') { fs.writeFileSync(OUT, text); console.log(`wrote ${OUT}`); process.exit(0); }
const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
if (old === text) { console.log('ok    song durations up to date'); process.exit(0); }
const was = old ? JSON.parse(old).entries : {};
const changed = [...new Set([...Object.keys(sorted), ...Object.keys(was)].filter(k => JSON.stringify(sorted[k]) !== JSON.stringify(was[k])).map(k => (sorted[k] || was[k]).id))];
console.log(`FAIL  ${OUT} is stale (${changed.join(', ')}): run node tools/song-durations.mjs write`);
process.exit(1);
